"""Canonical Normalized Transaction Models."""

from datetime import datetime
from decimal import Decimal
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field, field_validator
from cryptotrace.schemas.common import BlockchainType, TransactionStatus
from cryptotrace.schemas.provenance import DataSourceProvenance
from cryptotrace.schemas.token import TokenTransfer
from cryptotrace.schemas.utxo import UTXOInput, UTXOOutput


class CanonicalTransaction(BaseModel):
    """Universal canonical transaction schema preserving chain-specific semantics."""

    # Core Identifiers
    chain_id: str = Field(..., description="Network chain ID (e.g. 'btc-mainnet', '1')")
    blockchain: BlockchainType = Field(..., description="Blockchain name ('bitcoin', 'ethereum')")
    tx_hash: str = Field(..., description="Unique transaction hash")
    block_number: int = Field(..., ge=0, description="Block height containing transaction")
    block_hash: str = Field(..., description="Hash of the block containing the transaction")
    timestamp: datetime = Field(..., description="Block timestamp (UTC)")

    # Universal Flow References
    sender_references: List[str] = Field(
        ...,
        description="List of sending addresses or input references",
    )
    recipient_references: List[str] = Field(
        ...,
        description="List of recipient addresses or output references",
    )
    asset_symbol: str = Field(
        default="NATIVE",
        description="Asset symbol (e.g. 'BTC', 'ETH', or ERC20 token symbol)",
    )
    contract_address: Optional[str] = Field(
        None,
        description="Smart contract address if token or contract interaction",
    )
    amount: Decimal = Field(
        ...,
        description="Total primary transferred value as Decimal",
    )
    fee: Decimal = Field(
        default=Decimal("0"),
        description="Transaction fee paid to miners/validators",
    )
    status: TransactionStatus = Field(
        default=TransactionStatus.CONFIRMED,
        description="Finality status",
    )
    confirmations: int = Field(
        default=0,
        ge=0,
        description="Number of confirmations at retrieval time",
    )

    # Provenance
    provenance: DataSourceProvenance = Field(
        ...,
        description="Cryptographic and provider audit provenance",
    )

    # Bitcoin-Specific UTXO Architecture Semantics
    inputs: List[UTXOInput] = Field(
        default_factory=list,
        description="Bitcoin input UTXOs consumed by this transaction",
    )
    outputs: List[UTXOOutput] = Field(
        default_factory=list,
        description="Bitcoin output UTXOs generated by this transaction",
    )
    vsize: Optional[int] = Field(None, description="Virtual size in vbytes (Bitcoin)")
    locktime: Optional[int] = Field(None, description="Bitcoin locktime")

    # Ethereum-Specific Account Architecture Semantics
    from_address: Optional[str] = Field(None, description="Direct sender wallet/EOA (Ethereum)")
    to_address: Optional[str] = Field(None, description="Direct recipient wallet/contract (Ethereum)")
    gas_used: Optional[int] = Field(None, description="Gas consumed")
    gas_price_gwei: Optional[Decimal] = Field(None, description="Effective gas price in Gwei")
    nonce: Optional[int] = Field(None, description="Sender account nonce")
    input_data: Optional[str] = Field(None, description="Call data / bytecode")
    is_contract_interaction: bool = Field(default=False, description="Whether recipient is a contract")
    token_transfers: List[TokenTransfer] = Field(
        default_factory=list,
        description="Associated ERC-20 transfers emitted in transaction logs",
    )
    internal_traces: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="Internal VM message calls / traces",
    )

    @field_validator("amount", "fee", mode="before")
    @classmethod
    def validate_decimals(cls, val):
        if val is None:
            return Decimal("0")
        if isinstance(val, (int, float, str)):
            return Decimal(str(val))
        return val


class TransactionSummary(BaseModel):
    """Concise transaction summary for list representations and investigations."""

    chain_id: str
    blockchain: BlockchainType
    tx_hash: str
    block_number: int
    timestamp: datetime
    senders: List[str]
    recipients: List[str]
    asset_symbol: str
    amount: Decimal
    fee: Decimal
    status: TransactionStatus
    confirmations: int
    is_fixture: bool
