"""Bitcoin UTXO (Unspent Transaction Output) schemas."""

from decimal import Decimal
from typing import List, Optional
from pydantic import BaseModel, Field, field_validator


class UTXOInput(BaseModel):
    """Reference to an unspent output being consumed by a transaction."""

    prev_tx_hash: str = Field(..., description="Hash of the transaction creating this output")
    vout: int = Field(..., ge=0, description="Index of the output in the previous transaction")
    address: Optional[str] = Field(None, description="Owner address unlocking the output")
    amount_sats: int = Field(..., ge=0, description="Output value in satoshis")
    amount_btc: Decimal = Field(..., description="Output value in BTC (exact decimal)")
    sequence: Optional[int] = Field(None, description="Sequence number for RBF/timelocks")
    script_sig: Optional[str] = Field(None, description="Unlocking script")
    witness: List[str] = Field(default_factory=list, description="SegWit witness items")

    @field_validator("amount_btc", mode="before")
    @classmethod
    def validate_amount_btc(cls, val):
        if isinstance(val, (int, float, str)):
            return Decimal(str(val))
        return val


class UTXOOutput(BaseModel):
    """Output generated by a Bitcoin transaction."""

    vout: int = Field(..., ge=0, description="Output index in the transaction")
    address: Optional[str] = Field(None, description="Destination address (None for OP_RETURN)")
    amount_sats: int = Field(..., ge=0, description="Output value in satoshis")
    amount_btc: Decimal = Field(..., description="Output value in BTC (exact decimal)")
    script_pubkey: Optional[str] = Field(None, description="Locking script hex")
    script_type: Optional[str] = Field(None, description="Script type (e.g. p2pkh, p2wpkh, p2tr)")
    is_spent: bool = Field(default=False, description="Whether this output has been spent")
    spending_tx_hash: Optional[str] = Field(None, description="Transaction hash that spent this output")

    @field_validator("amount_btc", mode="before")
    @classmethod
    def validate_amount_btc(cls, val):
        if isinstance(val, (int, float, str)):
            return Decimal(str(val))
        return val


class UTXORecord(BaseModel):
    """Standalone UTXO representation for address balances and trace queries."""

    tx_hash: str
    vout: int
    address: str
    amount_sats: int
    amount_btc: Decimal
    block_height: Optional[int] = None
    confirmations: int = 0
    is_spent: bool = False
